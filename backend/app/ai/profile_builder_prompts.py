"""Onboarding step 1: turn the user's own plain-text description of their
work into a structured SearchProfile draft (see app/schemas/profile_draft.py).
Separate from app/ai/prompts.py (lead analysis) — different job, different
JSON contract, but the same "strict JSON schema, no markdown" discipline.
"""
from app.models.enums import KeywordCategory

_CATEGORIES = ", ".join(c.value for c in KeywordCategory)

PROFILE_DRAFT_SYSTEM_PROMPT = f"""Пользователь только что описал своими словами, чем он занимается и каких
клиентов хочет найти. Твоя задача — превратить это описание в структурированный
профиль поиска клиентов (Search Profile).

Действуй так:
1. Определи профессию/специализацию одной короткой фразой.
2. Перечисли конкретные услуги, которые предоставляет пользователь — короткими
   фразами, как их обычно называют в объявлениях (например: "дизайн карточек",
   "инфографика", "разработка сайтов", "настройка таргетированной рекламы").
3. Предложи 4-8 формулировок заказов, которые пользователь, скорее всего, хочет
   получать (suggested_orders) — короткие фразы вида "Нужен дизайнер карточек",
   "Ищу таргетолога для запуска рекламы".
4. Предложи 3-6 типичных исключений для этой профессии (suggested_exclusions) —
   то, что обычно НЕ интересно специалисту в этой сфере (вакансии в штат,
   стажировки, работа за отзыв, смежные, но другие специализации, слишком
   мелкие заказы и т.п.), с учётом того, что написал пользователь.
5. Сгенерируй 15-30 ключевых слов и фраз для поиска релевантных сообщений
   (suggested_keywords), распределённых по категориям: {_CATEGORIES}.
   - direct_intent: прямые формулировки поиска исполнителя ("нужен ...", "ищу ...").
   - service: конкретные названия услуг пользователя.
   - project_type: типы проектов/задач в этой сфере.
   - problem: проблемы клиента, которые решает эта услуга.
   - hidden_intent: ситуации, предвещающие будущий заказ (запуск бизнеса, выход
     на новую площадку, недовольство текущим решением и т.п.).
   - exclusion: слова/фразы, снижающие релевантность (вакансия, стажировка,
     за отзыв, ищу работу и т.п.) — общие, не привязанные к профессии пользователя.
   Каждое ключевое слово — реальная фраза на русском языке, 1-4 слова, вес
   (weight) от 0.8 до 2.0 (выше — сильнее сигнал).
6. Сформулируй ai_profile_context — 2-4 предложения на русском, обобщающих,
   какие заказы нужны пользователю и какие не нужны. Это станет системным
   контекстом для дальнейшего AI-анализа входящих сообщений.
7. Сформулируй 4 коротких резюме для финального экрана онбординга:
   - summary_direct: кого именно ищем среди тех, кто ПРЯМО ищет исполнителя.
   - summary_potential: кого ищем среди тех, у кого есть подходящая задача, но
     без прямого запроса.
   - summary_hidden: какие ситуации скрытого спроса будем отслеживать.
   - summary_excluded: что не будем показывать (коротко, списком через запятую).

Возвращай ТОЛЬКО валидный JSON, без markdown, без пояснений вне JSON, ровно со
следующими полями:
{{
  "profession": "string",
  "services": ["string", ...],
  "suggested_orders": ["string", ...],
  "suggested_exclusions": ["string", ...],
  "suggested_keywords": [{{"text": "string", "category": "direct_intent", "weight": 1.5}}, ...],
  "ai_profile_context": "string",
  "summary_direct": "string",
  "summary_potential": "string",
  "summary_hidden": "string",
  "summary_excluded": "string"
}}"""


def build_profile_draft_user_prompt(description: str) -> str:
    return (
        f"Описание пользователя:\n{description}\n\n"
        "Верни только JSON по описанной выше схеме."
    )
